#!/usr/bin/env python3
"""Generate client instructions from shared rules and client-specific documents."""

import argparse
import fcntl
import os
from itertools import islice
from pathlib import Path
import stat
import sys
import tempfile

TEXT_BYTES_MAX = 131_072
PRIVATE_FILE_MODE = 0o600
SKILL_COUNT_MAX = 64
CONFIGURATION_ROOT = Path(__file__).resolve().parent


def read_bounded(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Expected a regular, non-symlink instruction file: {path}")
    with path.open("rb") as stream:
        content = stream.read(TEXT_BYTES_MAX + 1)
    if len(content) > TEXT_BYTES_MAX or b"\0" in content:
        raise ValueError(f"Instruction file exceeds the text limit or contains NUL: {path}")
    return content


def render_outputs(configuration_root):
    home = Path.home()
    sources = [configuration_root / "shared/AGENTS.md", configuration_root / "opencode/AGENTS.md"]
    contents = []
    for source in sources:
        content = read_bounded(source).decode("utf-8").strip()
        if not content:
            raise ValueError(f"Instruction source is empty: {source}")
        contents.append(content)
    shared, opencode_runtime = contents
    outputs = [
        (home / ".pi/agent/SYSTEM.md", shared),
        (home / ".config/opencode/AGENTS.md", opencode_runtime + "\n\n" + shared),
    ]
    rendered = []
    for target, content in outputs:
        source_relative = os.path.relpath(configuration_root, target.parent.resolve())
        header = f"<!-- Generated by {source_relative}/build.py; paths relative to this file. Edit canonical sources there, then rebuild. -->\n\n"
        encoded = (header + content + "\n").encode("utf-8")
        if len(encoded) > TEXT_BYTES_MAX:
            raise ValueError(f"Generated instruction file exceeds the text limit: {target}")
        rendered.append((target, encoded))
    return rendered


def write_atomic(target, content, mode):
    descriptor, temporary_name = tempfile.mkstemp(prefix=".ai-build-", dir=target.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            os.fchmod(stream.fileno(), mode)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)


def build(configuration_root, check=False):
    outputs = render_outputs(configuration_root)
    changes = []
    for target, content in outputs:
        if target.is_symlink():
            raise ValueError(f"Refusing to overwrite a symlink instruction target: {target}")
        previous = read_bounded(target) if target.exists() else None
        if previous == content:
            continue
        mode = stat.S_IMODE(target.stat().st_mode) if previous is not None else PRIVATE_FILE_MODE
        changes.append((target, content, previous, mode))
    if check:
        if changes:
            raise ValueError("Generated instructions are stale: " + ", ".join(str(change[0]) for change in changes))
        return
    replaced = []
    try:
        for target, content, previous, mode in changes:
            target.parent.mkdir(parents=True, exist_ok=True)
            write_atomic(target, content, mode)
            replaced.append((target, previous, mode))
    except OSError as error:
        failures = []
        for target, previous, mode in reversed(replaced):
            try:
                if previous is None:
                    target.unlink(missing_ok=True)
                else:
                    write_atomic(target, previous, mode)
            except OSError:
                failures.append(str(target))
        if failures:
            raise RuntimeError("Build failed; rollback also failed for: " + ", ".join(failures)) from error
        raise


def plan_links(configuration_root):
    home = Path.home()
    shared = configuration_root / "shared/skills"
    if shared.is_symlink() or not shared.is_dir():
        raise ValueError(f"Expected a canonical shared skill directory: {shared}")
    skills = list(islice(shared.iterdir(), SKILL_COUNT_MAX + 1))
    if not skills or len(skills) > SKILL_COUNT_MAX:
        raise ValueError("Shared skill collection is empty or exceeds the link limit")
    workspace = configuration_root / "pi/AGENTS.md"
    if not read_bounded(workspace).decode("utf-8").strip():
        raise ValueError("Pi workspace source is empty")
    desired = [(home / ".pi/AGENTS.md", workspace)]
    for skill in sorted(skills):
        definition = skill / "SKILL.md"
        if skill.is_symlink() or not skill.is_dir() or definition.is_symlink() or not definition.is_file():
            raise ValueError(f"Expected a canonical skill with SKILL.md: {skill}")
        for client in [home / ".pi/agent/skills", home / ".config/opencode/skills"]:
            desired.append((client / skill.name, skill))
    changes = []
    for link, source in desired:
        previous = None
        if link.is_symlink():
            if link.resolve() != source.resolve():
                raise ValueError(f"Refusing to retarget an unrelated symlink: {link}")
            previous = os.readlink(link)
        elif link.exists():
            raise ValueError(f"Refusing to replace a non-symlink client entry: {link}")
        relative = os.path.relpath(source, link.parent.resolve())
        if previous != relative:
            changes.append((link, relative, previous))
    return changes


def replace_link(link, target):
    with tempfile.TemporaryDirectory(prefix=".ai-link-", dir=link.parent) as directory:
        temporary = Path(directory) / "link"
        temporary.symlink_to(target)
        os.replace(temporary, link)


def install_links(changes, check=False):
    if check:
        if changes:
            raise ValueError("Managed links are missing or not relative: " + ", ".join(str(change[0]) for change in changes))
        return
    replaced = []
    try:
        for link, relative, previous in changes:
            if previous is None:
                if link.exists() or link.is_symlink():
                    raise ValueError(f"Client entry appeared after link planning: {link}")
            elif not link.is_symlink() or os.readlink(link) != previous:
                raise ValueError(f"Client link changed after link planning: {link}")
            link.parent.mkdir(parents=True, exist_ok=True)
            replaced.append((link, previous))
            replace_link(link, relative)
    except (OSError, ValueError) as error:
        failures = []
        for link, previous in reversed(replaced):
            try:
                if previous is None:
                    link.unlink(missing_ok=True)
                else:
                    replace_link(link, previous)
            except OSError:
                failures.append(str(link))
        if failures:
            raise RuntimeError("Link installation failed; rollback also failed for: " + ", ".join(failures)) from error
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without rewriting them")
    parser.add_argument("--links", action="store_true", help="Also create/check relative managed client links; never replace unrelated entries")
    arguments = parser.parse_args()
    try:
        descriptor = os.open(CONFIGURATION_ROOT / "build.lock", os.O_CREAT | os.O_WRONLY | os.O_NOFOLLOW, PRIVATE_FILE_MODE)
        with os.fdopen(descriptor, "w") as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise RuntimeError("Another shared-instruction build is running") from error
            changes = plan_links(CONFIGURATION_ROOT) if arguments.links else []
            build(CONFIGURATION_ROOT, arguments.check)
            if arguments.links:
                install_links(changes, arguments.check)
    except (OSError, UnicodeError, ValueError, RuntimeError) as error:
        print(f"Shared instruction build failed: {error}", file=sys.stderr)
        return 1
    print("Shared instructions verified." if arguments.check else "Shared instructions generated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
